DELIMITER $$

CREATE FUNCTION `Calculate_Strike_Rate`(
  runs INT,
  balls INT
)
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
  IF balls IS NULL OR balls = 0 THEN
    RETURN 0;
  END IF;

  RETURN ROUND((runs / balls) * 100, 2);
END $$

CREATE PROCEDURE `Get_Player_Runs`(IN pid INT)
BEGIN
  SELECT
    p.player_id,
    p.name,
    COALESCE(SUM(per.runs), 0) AS total_runs
  FROM `Player` p
  LEFT JOIN `Performance` per ON p.player_id = per.player_id
  WHERE p.player_id = pid
  GROUP BY p.player_id, p.name;
END $$

CREATE PROCEDURE `Generate_Rankings`()
BEGIN
  DELETE FROM `Ranking`;

  INSERT INTO `Ranking`(`format`, `rank_position`, `player_id`)
  SELECT
    'T20 (Domestic)' AS ranking_format,
    ranked_players.rank_num,
    ranked_players.player_id
  FROM (
    SELECT
      player_id,
      DENSE_RANK() OVER (ORDER BY SUM(runs) DESC) AS rank_num
    FROM `Performance`
    GROUP BY player_id
  ) ranked_players;
END $$

CREATE PROCEDURE `Transfer_Player_To_Team`(
  IN input_player_id INT,
  IN input_team_id INT
)
BEGIN
  DECLARE active_count INT DEFAULT 0;

  START TRANSACTION;

  SELECT COUNT(*)
  INTO active_count
  FROM `Plays_For`
  WHERE player_id = input_player_id
    AND team_id = input_team_id
    AND end_date IS NULL;

  IF active_count > 0 THEN
    ROLLBACK;
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'Player is already active in this team';
  ELSE
    UPDATE `Plays_For`
    SET end_date = CURDATE()
    WHERE player_id = input_player_id
      AND end_date IS NULL;

    INSERT INTO `Plays_For`(`player_id`, `team_id`, `start_date`, `end_date`)
    VALUES (input_player_id, input_team_id, CURDATE(), NULL);

    COMMIT;
  END IF;
END $$

CREATE PROCEDURE `Cursor_Player_List`()
BEGIN
  DECLARE done INT DEFAULT FALSE;
  DECLARE pname VARCHAR(100);

  DECLARE cur CURSOR FOR
    SELECT name FROM `Player` ORDER BY name;

  DECLARE CONTINUE HANDLER FOR NOT FOUND SET done = TRUE;

  OPEN cur;

  read_loop: LOOP
    FETCH cur INTO pname;

    IF done THEN
      LEAVE read_loop;
    END IF;

    SELECT pname AS Player_Name;
  END LOOP;

  CLOSE cur;
END $$

